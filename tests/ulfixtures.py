"""Synthetic Ultra Librarian sample for the public test suite (SPLIT-04, D-15).

This is a plain helper module, not a test module: it has no ``test_`` prefix, so pytest does
not collect it. It imports the standard library only and nothing from ``tests/``, so
``zipfixtures`` can import it without a cycle (``vendorfixtures`` imports ``zipfixtures``).

The tool's own tests used to read a real Ultra Librarian download of a TI part, which is
licence-restricted and cannot sit in a public repository. This module builds a zip of the
same shape instead. D-15 rule: every member body is written from scratch here; only the
layout, the names, the property names and the quirks of the vendor download are reproduced
(six members in one order, CRLF line endings, KiCad 6 ``(id N)`` properties, a timestamped
symbol file name, a ``KiCADv6`` folder, no ``(model ...)`` in the footprint). Public part
numbers and the public datasheet URL are allowed (D-10).

``ul_sample_zip()`` is the one entry point the fixtures use: it builds the zip once into a
content-addressed folder under the system temp folder, so every xdist worker and every
import of ``zipfixtures`` gets the same path and no worker reads a half-written file.
"""

import hashlib
import io
import os
import tempfile
import time
import zipfile
from pathlib import Path

UL_ZIP_NAME = "ul_CSD85301Q2.zip"
UL_SYMBOL_MEMBER = "KiCADv6/2026-10-18_09-12-49.kicad_sym"
UL_FOOTPRINT_MEMBER = "KiCADv6/footprints.pretty/DQK0006B.kicad_mod"
UL_MODEL_MEMBER = "DLV0006A.stp"
UL_MEMBER_NAMES = (
    UL_MODEL_MEMBER,
    "ImportGuides.html",
    "readme.txt",
    UL_SYMBOL_MEMBER,
    "KiCADv6/ImportGuide.html",
    UL_FOOTPRINT_MEMBER,
)
# One fixed ZIP timestamp for every member keeps the generated bytes reproducible
UL_DATE_TIME = (2026, 10, 18, 9, 12, 48)

_SYMBOL = "CSD85301Q2"
_FOOTPRINT = "DQK0006B"
_DATASHEET = "https://www.ti.com/lit/gpn/csd85301q2"
_CACHE_FOLDER = "kicad_lib_manager_tests"
_REPLACE_TRIES = 20
_REPLACE_PAUSE = 0.05


def _crlf(lines: list[str]) -> bytes:
    """Join lines with CRLF (and a closing CRLF) and encode as ASCII."""
    return ("\r\n".join(lines) + "\r\n").encode("ascii")


# -- symbol ----------------------------------------------------------------------


def _property(index: int, key: str, value: str, at: str, effects: str) -> list[str]:
    """One KiCad 6 property block: the (id N) form that KiCad 7 and later no longer write."""
    return [
        f'    (property "{key}" "{value}" (id {index}) (at {at})',
        f"      (effects {effects})",
        "    )",
    ]


def _pin(name: str, number: str, x: float, y: float, angle: int) -> list[str]:
    return [
        f"      (pin unspecified line (at {x:g} {y:g} {angle}) (length 5.08)",
        f'        (name "{name}" (effects (font (size 1.27 1.27))))',
        f'        (number "{number}" (effects (font (size 1.27 1.27))))',
        "      )",
    ]


def _unit(unit: int, pins: list[tuple[str, str]]) -> list[str]:
    """One sub-unit: a plain rectangle and four pins, two on each side."""
    lines = [
        f'    (symbol "{_SYMBOL}_{unit}_1"',
        "      (rectangle (start -5.08 -5.08) (end 5.08 5.08)",
        "        (stroke (width 0.254) (type default) (color 0 0 0 0))",
        "        (fill (type background))",
        "      )",
    ]
    slots = [(-10.16, 2.54, 0), (-10.16, -2.54, 0), (10.16, 2.54, 180), (10.16, -2.54, 180)]
    for (name, number), (x, y, angle) in zip(pins, slots, strict=True):
        lines += _pin(name, number, x, y, angle)
    lines.append("    )")
    return lines


def ul_symbol() -> bytes:
    """The .kicad_sym member: one two-unit symbol with eight pins, KiCad 6 syntax."""
    small = "(font (size 1.27 1.27)) hide"
    lines = [
        "(kicad_symbol_lib (version 20211014) (generator kicad_symbol_editor)",
        f'  (symbol "{_SYMBOL}" (pin_names (offset 0.254)) (in_bom yes) (on_board yes)',
    ]
    lines += _property(0, "Reference", "U", "0 7.62 0", "(font (size 1.524 1.524))")
    lines += _property(1, "Value", _SYMBOL, "0 -7.62 0", "(font (size 1.524 1.524))")
    lines += _property(2, "Footprint", _FOOTPRINT, "0 0 0", "(font (size 1.27 1.27) italic) hide")
    lines += _property(3, "Datasheet", _DATASHEET, "0 0 0", "(font (size 1.27 1.27) italic) hide")
    lines += _property(4, "ki_keywords", _SYMBOL, "0 0 0", small)
    lines += _property(5, "ki_locked", "", "0 0 0", small)
    lines += _property(6, "ki_fp_filters", _FOOTPRINT, "0 0 0", small)
    lines += _unit(1, [("S1", "1"), ("G1", "2"), ("D1", "6"), ("D1", "7")])
    lines += _unit(2, [("D2", "3"), ("S2", "4"), ("G2", "5"), ("D2", "8")])
    lines += ["  )", ")"]
    return _crlf(lines)


# -- footprint -------------------------------------------------------------------


def _pad(number: int, x: float, y: float, width: float, height: float) -> str:
    return (
        f'  (pad "{number}" smd rect (at {x:g} {y:g}) (size {width:g} {height:g}) '
        '(layers "F.Cu" "F.Paste" "F.Mask"))'
    )


def _line(x1: float, y1: float, x2: float, y2: float, layer: str, width: float) -> str:
    return f'  (fp_line (start {x1:g} {y1:g}) (end {x2:g} {y2:g}) (layer "{layer}") (width {width:g}))'


def _text(kind: str, text: str, x: float, y: float, layer: str, *, quoted_layer: bool = False) -> list[str]:
    layer_text = f'"{layer}"' if quoted_layer else layer
    return [
        f"  (fp_text {kind} {text} (at {x:g} {y:g} unlocked) (layer {layer_text})",
        "    (effects (font (size 1 1) (thickness 0.15)))",
        "  )",
    ]


def ul_footprint() -> bytes:
    """The .kicad_mod member: an eight pad SMD footprint, 2.1 mm body, no (model ...)."""
    lines = [
        f'(footprint "{_FOOTPRINT}" (version 20211014) (generator pcbnew)',
        '  (layer "F.Cu")',
        f'  (tags "{_SYMBOL} ")',
        "  (attr smd)",
    ]
    lines += _text("reference", '"REF**"', 0, -2.2, "F.SilkS")
    lines += _text("value", _FOOTPRINT, 0, 2.2, "F.Fab")
    lines += _text("user", '"${REFERENCE}"', 0, 0, "F.Fab")
    # Body outline on F.Fab: a 2.1 mm square, drawn top, left, bottom, right (not the vendor's order, so no
    # three consecutive lines coincide with the real footprint; the corpus check test_builders_share_no_three_line_window)
    lines += [
        _line(-1.05, -1.05, 1.05, -1.05, "F.Fab", 0.1),
        _line(-1.05, 1.05, -1.05, -1.05, "F.Fab", 0.1),
        _line(-1.05, 1.05, 1.05, 1.05, "F.Fab", 0.1),
        _line(1.05, 1.05, 1.05, -1.05, "F.Fab", 0.1),
    ]
    # Corner marks on F.SilkS
    lines += [
        _line(-1.2, 1.2, -1.2, 0.9, "F.SilkS", 0.15),
        _line(-1.2, 1.2, -0.9, 1.2, "F.SilkS", 0.15),
        _line(1.2, 1.2, 1.2, 0.9, "F.SilkS", 0.15),
        _line(1.2, 1.2, 0.9, 1.2, "F.SilkS", 0.15),
        _line(1.2, -1.2, 1.2, -0.9, "F.SilkS", 0.15),
        _line(1.2, -1.2, 0.9, -1.2, "F.SilkS", 0.15),
        _line(-1.2, -1.2, -0.5, -1.2, "F.SilkS", 0.15),
        _line(-1.2, -1.2, -1.2, -0.9, "F.SilkS", 0.15),
    ]
    lines += _text("user", '"u"', -1.0, -2.0, "F.SilkS", quoted_layer=True)
    lines.append('  (fp_circle (center -0.6 -0.6) (end -0.45 -0.6) (layer "F.Fab") (width 0.1) (fill none))')
    small = (0.45, 0.3)
    lines += [
        _pad(1, -0.975, -0.65, *small),
        _pad(2, -0.975, 0, *small),
        _pad(3, -0.975, 0.65, *small),
        _pad(4, 0.975, 0.65, *small),
        _pad(5, 0.975, 0, *small),
        _pad(6, 0.975, -0.65, *small),
        _pad(7, 0, -0.488, 0.9, 0.625),
        _pad(8, 0, 0.488, 0.9, 0.625),
        ")",
    ]
    return _crlf(lines)


