def _readme() -> bytes:
    return _crlf(
        [
            "Notes:",
            " ",
            "1. This archive is a synthetic stand-in written for the test suite.",
            "2. It reproduces the layout of a vendor download, not its content.",
        ]
    )


# -- zip -------------------------------------------------------------------------


def ul_members() -> list[tuple[zipfile.ZipInfo, bytes]]:
    """The six members in archive order, each with a fixed ZipInfo (date, deflate, system)."""
    bodies = {
        UL_MODEL_MEMBER: ul_model(),
        "ImportGuides.html": _import_guide_root(),
        "readme.txt": _readme(),
        UL_SYMBOL_MEMBER: ul_symbol(),
        "KiCADv6/ImportGuide.html": _import_guide_kicad(),
        UL_FOOTPRINT_MEMBER: ul_footprint(),
    }
    members = []
    for name in UL_MEMBER_NAMES:
        info = zipfile.ZipInfo(name, date_time=UL_DATE_TIME)
        info.compress_type = zipfile.ZIP_DEFLATED
        info.create_system = 0  # the platform would otherwise leak into the bytes
        members.append((info, bodies[name]))
    return members


def ul_zip_bytes() -> bytes:
    """The sample as zip bytes; two calls return identical bytes."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for info, data in ul_members():
            zf.writestr(info, data)
    return buffer.getvalue()


def ul_zip(path: Path) -> Path:
    """Write the sample to path (creating its folder) and return path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(ul_zip_bytes())
    return path


def _sha256_of(path: Path) -> str | None:
    """SHA-256 of the file, or None when it is missing or cannot be read right now."""
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def ul_sample_zip() -> Path:
    """Return the sample zip, built once per content hash under the system temp folder.

    The folder name is the first 12 hex characters of the SHA-256 of the bytes, so a changed
    builder gets a new folder and the same builder gets the same path in every process. The
    file is written under a temporary name and moved over the target with os.replace, so a
    parallel worker never reads half a zip. On Windows os.replace can fail while another
    worker holds the target open: the target is then re-read and accepted when its hash
    matches, else the move is retried.
    """
    data = ul_zip_bytes()
    digest = hashlib.sha256(data).hexdigest()
    target = Path(tempfile.gettempdir()) / _CACHE_FOLDER / digest[:12] / UL_ZIP_NAME
    if _sha256_of(target) == digest:
        return target
    target.parent.mkdir(parents=True, exist_ok=True)
    temp = target.with_name(f"{UL_ZIP_NAME}.tmp-{os.getpid()}")
    try:
        temp.write_bytes(data)
        for _ in range(_REPLACE_TRIES):
            try:
                os.replace(temp, target)
                return target
            except PermissionError:
                if _sha256_of(target) == digest:
                    return target
                time.sleep(_REPLACE_PAUSE)
        raise PermissionError(f"could not place the synthetic sample at {target}")
    finally:
        temp.unlink(missing_ok=True)
